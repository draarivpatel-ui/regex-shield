// Build the CommonJS entry point from the ESM sources.
//
// The ESM modules are the single source of truth. Each one is wrapped in a small
// module factory and wired through an in-file registry, which keeps the generated
// cjs/index.cjs dependency free and avoids duplicating logic. Run with --check in
// CI to prove the committed artifact matches the sources.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = join(SCRIPT_DIR, '..');
const TARGET = join(ROOT, 'cjs', 'index.cjs');

const MODULES = ['charset.mjs', 'parser.mjs', 'analyzer.mjs', 'witness.mjs', 'index.mjs'];

function transform(source, id) {
  const exports = [];
  let body = source;

  body = body.replace(/^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$/gm, (_match, names, spec) => {
    return `const {${names}} = __internalRequire('${spec}');`;
  });

  body = body.replace(/^export\s+(?:async\s+)?function\s+([A-Za-z0-9_$]+)/gm, (_match, name) => {
    exports.push({ exported: name, local: name });
    return `function ${name}`;
  });
  body = body.replace(/^export\s+class\s+([A-Za-z0-9_$]+)/gm, (_match, name) => {
    exports.push({ exported: name, local: name });
    return `class ${name}`;
  });
  body = body.replace(/^export\s+(const|let|var)\s+([A-Za-z0-9_$]+)/gm, (_match, keyword, name) => {
    exports.push({ exported: name, local: name });
    return `${keyword} ${name}`;
  });
  body = body.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (_match, names) => {
    for (const part of names.split(',')) {
      const trimmed = part.trim();
      if (trimmed.length === 0) continue;
      const aliasParts = trimmed.split(/\s+as\s+/);
      if (aliasParts.length === 2) exports.push({ exported: aliasParts[1].trim(), local: aliasParts[0].trim() });
      else exports.push({ exported: trimmed, local: trimmed });
    }
    return '';
  });

  if (/^export\s/m.test(body)) {
    throw new Error(`build-cjs: unhandled export form in ${id}`);
  }

  const tail = exports.length > 0
    ? exports.map((entry) => `__exports.${entry.exported} = ${entry.local};`).join('\n')
    : '';

  return { body: body.trimEnd(), tail };
}

function build() {
  const parts = [];
  parts.push("'use strict';");
  parts.push('// Generated by scripts/build-cjs.mjs from src/*.mjs. Do not edit directly.');
  parts.push('// Source of truth: src/*.mjs. Run "npm run build:cjs" after editing the ESM sources.');
  parts.push('const __internalModules = new Map();');
  parts.push('function __internalDefine(id, factory) {');
  parts.push('  __internalModules.set(id, { factory, exports: {}, loaded: false });');
  parts.push('}');
  parts.push('function __internalRequire(spec) {');
  parts.push("  const id = String(spec).replace(/^\\.\\//, '');");
  parts.push('  const entry = __internalModules.get(id);');
  parts.push("  if (!entry) throw new Error('regex-shield: unknown internal module ' + spec);");
  parts.push('  if (!entry.loaded) {');
  parts.push('    entry.loaded = true;');
  parts.push('    entry.factory(entry.exports, __internalRequire);');
  parts.push('  }');
  parts.push('  return entry.exports;');
  parts.push('}');
  for (const id of MODULES) {
    const source = readFileSync(join(ROOT, 'src', id), 'utf8');
    const { body, tail } = transform(source, id);
    parts.push(`__internalDefine('${id}', function (__exports, __internalRequire) {`);
    parts.push(`// ---- src/${id} ----`);
    parts.push(body);
    if (tail) parts.push(tail);
    parts.push('});');
  }
  parts.push("module.exports = __internalRequire('./index.mjs');");
  parts.push('');
  return parts.join('\n');
}

const output = build();
const check = process.argv.includes('--check');

if (check) {
  if (!existsSync(TARGET)) {
    process.stderr.write('cjs/index.cjs is missing; run npm run build:cjs\n');
    process.exit(1);
  }
  const current = readFileSync(TARGET, 'utf8');
  if (current !== output) {
    process.stderr.write('cjs/index.cjs is out of date; run npm run build:cjs\n');
    process.exit(1);
  }
  process.stdout.write('cjs/index.cjs is up to date\n');
} else {
  writeFileSync(TARGET, output);
  process.stdout.write(`wrote ${TARGET} (${output.length} bytes)\n`);
}
